###Find repeat customers

SELECT
    CustomerID,
    COUNT(DISTINCT Invoice) AS total_orders,
    ROUND(SUM(Revenue), 2) AS net_revenue
FROM ecommerce_sales
WHERE CustomerID IS NOT NULL
GROUP BY CustomerID
HAVING COUNT(DISTINCT Invoice) >= 10
ORDER BY total_orders DESC
LIMIT 10;


