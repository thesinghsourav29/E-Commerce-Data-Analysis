###Which countries have the most orders?

SELECT
    Country,
    COUNT(DISTINCT Invoice) AS total_orders,
    ROUND(SUM(Revenue), 2) AS total_revenue,
    ROUND(
        SUM(Revenue) / COUNT(DISTINCT Invoice),
        2
    ) AS revenue_per_order
FROM ecommerce_sales
GROUP BY Country
ORDER BY total_orders DESC
LIMIT 10;


###ustomers by Net Revenu


SELECT
    CustomerID,
    COUNT(DISTINCT Invoice) AS total_orders,
    ROUND(SUM(Revenue), 2) AS total_revenue
FROM ecommerce_sales
WHERE CustomerID IS NOT NULL
GROUP BY CustomerID
ORDER BY total_revenue DESC
LIMIT 10;

####Sales vs. returns by month


SELECT
    Month,
    SUM(CASE
        WHEN TransactionType = 'Sale' THEN Revenue
        ELSE 0
    END) AS sales_revenue,
    SUM(CASE
        WHEN TransactionType = 'Return' THEN ABS(Revenue)
        ELSE 0
    END) AS returned_value,
    ROUND(SUM(Revenue), 2) AS net_revenue
FROM ecommerce_sales
GROUP BY Month
ORDER BY Month;


